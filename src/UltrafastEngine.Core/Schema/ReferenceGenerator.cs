using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace UltrafastEngine.Schema
{
    /// <summary>
    /// Markdown reference tables generated from the option registry (docs/reference/options.md, written by
    /// <c>ultrafast reference</c>): every element, instrument, model and spec section with every key, its type, unit,
    /// default and meaning. Generated, so it cannot drift from the engine.
    /// </summary>
    public static class ReferenceGenerator
    {
        private static readonly (string Category, string Title, string Intro)[] Sections =
        {
            ("system", "System file", "Top-level keys of a `.ufs` system file."),
            ("run", "Run spec", "Top-level keys of a run spec (`run.json`). Plugins add keys (see *Plugin keys*)."),
            ("pulse", "Pulse", "`run.pulse`."),
            ("grid", "Grid", "`run.grid`."),
            ("physics", "Physics", "`run.physics`."),
            ("stepper", "Stepper", "`run.stepper`."),
            ("outputs", "Outputs", "`run.outputs`."),
            ("element", "Elements", "`system.elements[]`, by `type`. Every element also accepts the common element keys."),
            ("instrument", "Instruments", "`run.instruments[]`, by `kind`. Every instrument also accepts the common instrument keys."),
            ("group", "Common key groups", "Keys shared by several components."),
            ("instrumentCommon", "Common instrument keys", "Keys every instrument accepts (core and plugins)."),
            ("runTop", "Plugin keys (run spec)", "Top-level run-spec keys provided by plugins."),
        };

        public static string Markdown(IEnumerable<string> origins = null)
        {
            var only = origins == null ? null : new HashSet<string>(origins, StringComparer.OrdinalIgnoreCase);
            var sb = new StringBuilder();
            sb.AppendLine("# Option reference (generated)");
            sb.AppendLine();
            sb.AppendLine("<!-- Generated by `ultrafast reference -o docs/reference/options.md` from the engine's option registry. Do not edit by hand. -->");
            sb.AppendLine();
            sb.AppendLine("Every key the engine reads, with its JSON type, SI unit, default and meaning. The same registry produces the");
            sb.AppendLine("JSON Schemas (`schemas/`, [Schemas](schema.md)) and the unknown-key warnings, so this page is complete by construction.");
            sb.AppendLine("Units: the key suffix names the unit (`lengthM` metres, `durationFwhmS` seconds, `gddFs2` fs²).");
            sb.AppendLine();
            var all = OptionRegistry.All.Where(s => only == null || only.Contains(s.Origin)).ToList();
            foreach (var (cat, title, intro) in Sections)
            {
                var specs = all.Where(s => s.Category == cat).OrderBy(s => s.Name, StringComparer.OrdinalIgnoreCase).ToList();
                if (specs.Count == 0) continue;
                sb.AppendLine("## " + title);
                sb.AppendLine();
                sb.AppendLine(intro);
                sb.AppendLine();
                foreach (var s in specs) Component(sb, s, specs.Count > 1 || s.Name != "");
            }
            // nested objects (pump, sampling, imaging, ...) and model kinds
            var nested = all.Where(s => s.Name == "" && !Sections.Any(x => x.Category == s.Category) && !s.Category.StartsWith("model:")).OrderBy(s => s.Category, StringComparer.OrdinalIgnoreCase).ToList();
            if (nested.Count > 0)
            {
                sb.AppendLine("## Nested objects");
                sb.AppendLine();
                foreach (var s in nested) { sb.AppendLine("### `" + s.Category + "`"); sb.AppendLine(); Body(sb, s); }
            }
            var models = all.Where(s => s.Category.StartsWith("model:")).OrderBy(s => s.Category).ThenBy(s => s.Name).ToList();
            if (models.Count > 0)
            {
                sb.AppendLine("## Model kinds");
                sb.AppendLine();
                sb.AppendLine("Models with declared parameters (other kinds are described in [Models](models.md)). Every model object also takes `kind` and optionally `name`, `source`, `reference`.");
                sb.AppendLine();
                foreach (var s in models) { sb.AppendLine("### " + s.Category.Substring(6) + " / `" + s.Name + "`"); sb.AppendLine(); Body(sb, s); }
            }
            return sb.ToString();
        }

        private static void Component(StringBuilder sb, ComponentSpec s, bool heading)
        {
            if (heading && s.Name != "")
            {
                sb.AppendLine("### `" + s.Name + "`" + (s.Aliases.Length > 0 ? " (also " + string.Join(", ", s.Aliases.Select(a => "`" + a + "`")) + ")" : "") + (s.Origin != "core" ? " — plugin: " + s.Origin : ""));
                sb.AppendLine();
            }
            Body(sb, s);
        }

        private static void Body(StringBuilder sb, ComponentSpec s)
        {
            if (!string.IsNullOrEmpty(s.Summary)) { sb.AppendLine(s.Summary + (string.IsNullOrEmpty(s.Doc) ? "" : " More: [" + s.Doc.Replace("reference/", "") + "](" + Link(s.Doc) + ")")); sb.AppendLine(); }
            if (s.Includes.Count > 0) { sb.AppendLine("Also accepts: " + string.Join(", ", s.Includes.Select(g => "`" + g + "`")) + " (see *Common key groups*)."); sb.AppendLine(); }
            if (s.Params.Count == 0) { sb.AppendLine("No parameters of its own."); sb.AppendLine(); return; }
            sb.AppendLine("| key | type | unit | default | meaning |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (var p in s.Params)
            {
                string type = TypeName(p);
                string desc = Esc(p.Description) + (p.Required ? " **Required.**" : "") + (p.DeprecatedBy != null ? " *Deprecated: use " + p.DeprecatedBy + ".*" : "")
                              + (p.Aliases.Length > 0 ? " Also: " + string.Join(", ", p.Aliases.Select(a => "`" + a + "`")) + "." : "");
                sb.AppendLine("| `" + p.Name + "` | " + type + " | " + Esc(p.Unit) + " | " + Esc(p.Default ?? "") + " | " + desc + " |");
            }
            sb.AppendLine();
        }

        /// <summary>Doc names used in the option declarations -> the page in docs/reference that has the section.</summary>
        private static readonly Dictionary<string, string> PageMap = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            { "elements", "system-file" }, { "solvers", "nonlinear" }, { "spatial-models", "transverse" }
        };
        /// <summary>Every reference page lives in docs/reference (Stage 1.8).</summary>
        private static readonly HashSet<string> InReference = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "plugins", "schema", "options", "system-file", "run-spec", "models", "materials", "coatings", "nonlinear", "active-elements", "crystals", "gain",
            "oscillators", "spatial-properties", "transverse", "instruments", "results", "c-api", "python", "extending", "components", "gases", "ionization",
            "retrieval", "studies", "speed", "python-api"
        };

        private static string Link(string doc)
        {
            if (!doc.StartsWith("reference/")) return "../" + doc;
            var rest = doc.Substring("reference/".Length);
            int h = rest.IndexOf('#');
            string page = (h >= 0 ? rest.Substring(0, h) : rest).Replace(".md", ""), anchor = h >= 0 ? rest.Substring(h) : "";
            if (PageMap.TryGetValue(page, out var mapped)) { page = mapped; anchor = ""; }
            if (InReference.Contains(page)) return page + ".md" + anchor;
            return "../" + page + ".md" + anchor;
        }

        private static string TypeName(ParamSpec p)
        {
            switch (p.Type)
            {
                case ParamType.String: return p.Enum != null ? string.Join(" \\| ", p.Enum.Select(e => "`\"" + e + "\"`")) : "string";
                case ParamType.NumberOrArray: return "number or array";
                case ParamType.Model: return "model" + (p.ModelCategory != null ? " (" + p.ModelCategory + ")" : "");
                case ParamType.Object: return p.ObjectRef != null && !p.FreeForm ? "object (`" + p.ObjectRef + "`)" : "object";
                case ParamType.Array: return p.ObjectRef != null ? "array of `" + p.ObjectRef + "`" : "array";
                default: return p.Type.ToString().ToLowerInvariant();
            }
        }

        private static string Esc(string s) => (s ?? "").Replace("|", "\\|").Replace("\n", " ");
    }
}
