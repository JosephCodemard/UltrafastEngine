// Catalogue.cs -- the material catalogue: every material number of the engine, with its provenance.
//
// What it does: loads the catalogue files (JSON with comments) that are embedded in the assembly under Data/materials/{solids,gases,raman,gain,crystals}/
// and, on top of them, the user's own files (folder $ULTRAFAST_MATERIALS, default ~/.ultrafast/materials; a file replaces the quantities
// it names, with a notice). MaterialLibrary, GasData and the Raman models read their numbers from here; nothing is hard-coded in C#.
//
// Classes:
//   CatalogueEntry     one material, gas, Raman model, gain medium or chi(2) crystal: Id, Kind ("solid" | "gas" | "raman" | "gain" | "crystal"), Aliases, ListOrder, Notes, Quantities.
//   CatalogueQuantity  one quantity of an entry ("index", "n2", "rotation", ...): its numbers (Json), Source, Status, uncertainty, Origin.
//   CatalogueStatus    Verified (the number was read from the source), Approximate (typical / fitted), Unverified (not checked).
//   Catalogue          static: Find(nameOrAlias), Get, Entries(kind), Notices (user overrides), Problems() (lint), Reload(userFolder) for tests.
//
// File format: docs/reference/materials-catalogue.md (generated by `ultrafast reference materials`) and Data/materials/README.md.
// Units are in the key names (valueM2PerW, tau1S, ionizationEv, rotationalConstantBPerCm); coefficients keep the units of their source.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using UltrafastEngine.Models;
using UltrafastEngine.Serialization;

namespace UltrafastEngine.Materials
{
    /// <summary>How far a catalogue number has been checked against its source.</summary>
    public enum CatalogueStatus
    {
        /// <summary>Read from the cited source and compared (the check is recorded in the entry).</summary>
        Verified = 0,
        /// <summary>A typical, rounded or fitted value; good to the stated uncertainty, not traced to one table.</summary>
        Approximate = 1,
        /// <summary>Not checked against any source yet (quoted from memory or from an earlier version of the code).</summary>
        Unverified = 2
    }

    /// <summary>One quantity of a catalogue entry: the numbers and where they come from.</summary>
    public sealed class CatalogueQuantity
    {
        public string EntryId { get; internal set; }
        public string Name { get; internal set; }
        /// <summary>The quantity's JSON object (numbers with units in their key names, plus the metadata keys).</summary>
        public JsonObject Json { get; internal set; }
        public string Source => Json.GetString("source", "");
        public CatalogueStatus Status { get; internal set; }
        /// <summary>Relative uncertainty (1-sigma-like spread of the literature), NaN when not stated.</summary>
        public double RelativeUncertainty => Json.GetDouble("relativeUncertainty", double.NaN);
        public string Uncertainty => Json.GetString("uncertainty", "");
        /// <summary>"built-in" or "user: path".</summary>
        public string Origin { get; internal set; } = "built-in";
        public bool IsUser => Origin.StartsWith("user", StringComparison.Ordinal);
        public string Path => EntryId + "." + Name;

        public bool Has(string key) => Json.Has(key);
        public double Number(string key) => Json.GetRequiredDouble(key, Path);
        public double Number(string key, double fallback) => Json.GetDouble(key, fallback);
        public double[] Array(string key) => Json.GetDoubleArray(key) ?? throw new ModelException("catalogue " + Path + ": missing array \"" + key + "\".");
        public string Text(string key, string fallback = null) => Json.GetString(key, fallback);

        /// <summary>One line for notes and reports: status, source, uncertainty.</summary>
        public string Citation()
        {
            string s = Status.ToString().ToUpperInvariant() + ": " + Source;
            if (!double.IsNaN(RelativeUncertainty)) s += string.Format(CultureInfo.InvariantCulture, " (uncertainty about {0:G2} %)", 100 * RelativeUncertainty);
            else if (Uncertainty.Length > 0) s += " (" + Uncertainty + ")";
            if (IsUser) s += " [" + Origin + "]";
            return s;
        }
    }

    /// <summary>One material, gas or Raman model of the catalogue.</summary>
    public sealed class CatalogueEntry
    {
        public string Id { get; internal set; }
        public string Kind { get; internal set; }
        public int ListOrder { get; internal set; }
        public string Description { get; internal set; }
        public string Notes { get; internal set; }
        public List<string> Aliases { get; } = new List<string>();
        public Dictionary<string, CatalogueQuantity> Quantities { get; } = new Dictionary<string, CatalogueQuantity>(StringComparer.OrdinalIgnoreCase);
        public string File { get; internal set; }
        /// <summary>The entry's file as parsed: entry-level fields that are not quantities (displayName, opticalClass, references, ...).</summary>
        public JsonObject Raw { get; internal set; }

        public bool Has(string quantity) => Quantities.ContainsKey(quantity);
        public CatalogueQuantity Q(string quantity) =>
            Quantities.TryGetValue(quantity, out var q) ? q : throw new ModelException("catalogue entry '" + Id + "' has no quantity \"" + quantity + "\" (" + File + ").");
        public CatalogueQuantity TryQ(string quantity) => Quantities.TryGetValue(quantity, out var q) ? q : null;
    }

    /// <summary>The material catalogue (see the file header). Thread-safe; loaded on first use.</summary>
    public static class Catalogue
    {
        private const string Prefix = "UltrafastEngine.Data.materials.";
        private static readonly string[] Kinds = { "solid", "gas", "raman", "gain", "crystal", "default" };

        private sealed class State
        {
            public readonly Dictionary<string, CatalogueEntry> ById = new Dictionary<string, CatalogueEntry>(StringComparer.OrdinalIgnoreCase);
            public readonly Dictionary<string, string> Alias = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            public readonly List<string> Notices = new List<string>();
            public readonly List<string> Problems = new List<string>();
            public readonly Dictionary<string, object> Cache = new Dictionary<string, object>();
        }

        private static readonly object Gate = new object();
        private static State _state;
        private static string _userFolderOverride;   // tests

        private static State S { get { lock (Gate) return _state ?? (_state = Load(UserFolder)); } }

        /// <summary>The folder with the user's own catalogue files ($ULTRAFAST_MATERIALS, else ~/.ultrafast/materials); may not exist.</summary>
        public static string UserFolder
        {
            get
            {
                if (_userFolderOverride != null) return _userFolderOverride;
                var env = Environment.GetEnvironmentVariable("ULTRAFAST_MATERIALS");
                if (env != null) return env;   // an empty value switches the user catalogue off
                var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
                return string.IsNullOrEmpty(home) ? "" : System.IO.Path.Combine(home, ".ultrafast", "materials");
            }
        }

        /// <summary>Notices about user files that replaced built-in quantities (shown in run notes by the compiler).</summary>
        public static IReadOnlyList<string> Notices => S.Notices;

        /// <summary>Format problems found while loading (empty for the shipped catalogue; the lint test asserts it).</summary>
        public static IReadOnlyList<string> Problems => S.Problems;

        /// <summary>Derived tables (GasData, index coefficients, ...) are built once per loaded catalogue: <paramref name="build"/> runs the first time for a key and the result is kept until the catalogue is reloaded.</summary>
        public static T Cached<T>(string key, Func<T> build) where T : class
        {
            var s = S;
            lock (s.Cache)
            {
                if (!s.Cache.TryGetValue(key, out var v)) s.Cache[key] = v = build();
                return (T)v;
            }
        }

        /// <summary>Reload with another user folder (null: the default). For tests.</summary>
        internal static void Reload(string userFolder)
        {
            lock (Gate) { _userFolderOverride = userFolder; _state = null; }
        }

        public static IEnumerable<CatalogueEntry> Entries(string kind = null) =>
            S.ById.Values.Where(e => kind == null || e.Kind == kind).OrderBy(e => e.ListOrder).ThenBy(e => e.Id, StringComparer.Ordinal);

        /// <summary>The entry for a name or alias (case-insensitive), or null.</summary>
        public static CatalogueEntry Find(string nameOrAlias)
        {
            var s = S;
            string n = (nameOrAlias ?? "").Trim();
            if (s.ById.TryGetValue(n, out var e)) return e;
            if (s.Alias.TryGetValue(n, out var id) && s.ById.TryGetValue(id, out e)) return e;
            return null;
        }

        public static CatalogueEntry Find(string nameOrAlias, string kind)
        {
            var e = Find(nameOrAlias);
            return e != null && e.Kind == kind ? e : null;
        }

        public static CatalogueEntry Get(string id, string kind) =>
            Find(id, kind) ?? throw new ModelException("catalogue: no " + kind + " entry '" + id + "'.");

        // ------------------------------------------------------------------------------------------------ loading

        private static State Load(string userFolder)
        {
            var st = new State();
            var asm = typeof(Catalogue).Assembly;
            foreach (var res in asm.GetManifestResourceNames().Where(r => r.StartsWith(Prefix, StringComparison.Ordinal) && r.EndsWith(".json", StringComparison.Ordinal)).OrderBy(r => r, StringComparer.Ordinal))
            {
                string text;
                using (var rs = asm.GetManifestResourceStream(res))
                using (var sr = new StreamReader(rs)) text = sr.ReadToEnd();
                Add(st, text, "built-in", res.Substring(Prefix.Length), user: false);
            }
            if (!string.IsNullOrEmpty(userFolder) && Directory.Exists(userFolder))
                foreach (var f in Directory.GetFiles(userFolder, "*.json", SearchOption.AllDirectories).OrderBy(x => x, StringComparer.Ordinal))
                    Add(st, File.ReadAllText(f), "user: " + f, f, user: true);
            return st;
        }

        private static void Add(State st, string text, string origin, string file, bool user)
        {
            JsonObject o;
            try { o = JsonValue.Parse(text).AsObject(); }
            catch (JsonException ex) { throw new ModelException("catalogue file " + file + ": " + ex.Message); }
            string id = o.GetString("id") ?? throw new ModelException("catalogue file " + file + ": missing \"id\".");
            st.ById.TryGetValue(id, out var existing);
            string kind = o.GetString("kind") ?? existing?.Kind;
            if (kind == null || !Kinds.Contains(kind)) throw new ModelException("catalogue file " + file + ": \"kind\" must be solid, gas, raman, gain, crystal or default.");
            if (existing != null && existing.Kind != kind) throw new ModelException("catalogue file " + file + ": '" + id + "' is a " + existing.Kind + " in the built-in catalogue.");
            var e = existing ?? new CatalogueEntry { Id = id, Kind = kind, File = file };
            if (existing == null) { st.ById[id] = e; e.Raw = o; }
            else foreach (var kv in o) if (kv.Key != "quantities") e.Raw.Set(kv.Key, kv.Value);
            if (o.Has("listOrder")) e.ListOrder = o.GetInt("listOrder", 1000);
            else if (existing == null) e.ListOrder = 1000;
            if (o.Has("description")) e.Description = o.GetString("description");
            if (o.Has("notes")) e.Notes = o.GetString("notes");
            if (o.Has("aliases"))
                foreach (var a in o.GetArray("aliases"))
                {
                    string al = a.AsString();
                    if (!e.Aliases.Contains(al)) e.Aliases.Add(al);
                    st.Alias[al] = id;
                }
            var qs = o.GetObject("quantities");
            if (qs == null) { st.Problems.Add(file + ": no \"quantities\""); return; }
            foreach (var kv in qs)
            {
                var qo = kv.Value.AsObject();
                var q = new CatalogueQuantity { EntryId = id, Name = kv.Key, Json = qo, Origin = origin };
                string status = qo.GetString("status", qo.Has("ref") ? "verified" : "");   // a "ref" quantity points at another entry, whose own quantities carry the status
                switch (status.ToLowerInvariant())
                {
                    case "verified": q.Status = CatalogueStatus.Verified; break;
                    case "approximate": q.Status = CatalogueStatus.Approximate; break;
                    case "unverified": q.Status = CatalogueStatus.Unverified; break;
                    default: q.Status = CatalogueStatus.Unverified; st.Problems.Add(file + ": " + id + "." + kv.Key + " has status \"" + status + "\" (verified | approximate | unverified)"); break;
                }
                if (!qo.Has("ref") && qo.GetString("source", "").Trim().Length == 0) st.Problems.Add(file + ": " + id + "." + kv.Key + " has no \"source\"");
                if (user && e.Quantities.ContainsKey(kv.Key))
                    st.Notices.Add("user catalogue " + file + " replaces " + id + "." + kv.Key + " (" + e.Quantities[kv.Key].Status.ToString().ToLowerInvariant() + " built-in value)");
                e.Quantities[kv.Key] = q;
            }
        }

        /// <summary>The embedded catalogue files' text, by relative path (for the generated reference page and the lint test).</summary>
        internal static IEnumerable<KeyValuePair<string, string>> EmbeddedFiles()
        {
            var asm = typeof(Catalogue).Assembly;
            foreach (var res in asm.GetManifestResourceNames().Where(r => r.StartsWith(Prefix, StringComparison.Ordinal) && r.EndsWith(".json", StringComparison.Ordinal)).OrderBy(r => r, StringComparer.Ordinal))
                using (var rs = asm.GetManifestResourceStream(res))
                using (var sr = new StreamReader(rs)) yield return new KeyValuePair<string, string>(res.Substring(Prefix.Length), sr.ReadToEnd());
        }
    }
}
