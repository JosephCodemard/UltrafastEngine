// CatalogueReference.cs -- generates docs/reference/materials-catalogue.md from the shipped catalogue files.
//
// `ultrafast reference materials -o docs/reference/materials-catalogue.md` (part of /regen). It reads only the embedded files, never the
// user's own, so the page is the same on every machine. Layout: how to read it, counts by status, one table per material / gas / Raman model
// (quantity, values with their units, status, uncertainty, source), and the list of everything that is not verified yet.
//
//   CatalogueReference.Markdown() -> the page text
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using UltrafastEngine.Serialization;

namespace UltrafastEngine.Materials
{
    public static class CatalogueReference
    {
        private static readonly HashSet<string> Meta = new HashSet<string> { "source", "status", "uncertainty", "relativeUncertainty", "verification", "conditions", "name", "ref" };

#if NET
        private static string Num(double v) => v.ToString("R", CultureInfo.InvariantCulture);
#else
        // .NET Framework's "R" can print 17 digits for a value that 15 reproduce (56.306399999999996): use the shortest round-trip, as .NET does.
        private static string Num(double v)
        {
            foreach (var f in new[] { "G15", "G16", "G17" })
            {
                var t = v.ToString(f, CultureInfo.InvariantCulture);
                if (double.Parse(t, CultureInfo.InvariantCulture) == v) return t;
            }
            return v.ToString("G17", CultureInfo.InvariantCulture);
        }
#endif

        private static string Value(JsonValue v)
        {
            switch (v.Kind)
            {
                case JsonKind.Number: return Num(v.AsDouble());
                case JsonKind.String: return v.AsString();
                case JsonKind.Array:
                    var a = v.AsArray().ToList();
                    return a.Count > 6 ? "[" + string.Join(", ", a.Take(3).Select(Value)) + ", ... (" + a.Count + " values)]" : "[" + string.Join(", ", a.Select(Value)) + "]";
                case JsonKind.Bool: return v.AsBool() ? "true" : "false";
                default: return v.ToJson(false);
            }
        }

        private static string Cell(string s) => (s ?? "").Replace("|", "\\|").Replace("\n", " ");

        private sealed class Row { public string Entry, Kind, Quantity, Values, Status, Uncertainty, Source, Check; }

        public static string Markdown()
        {
            var rows = new List<Row>();
            var entries = new List<(string File, JsonObject O)>();
            foreach (var f in Catalogue.EmbeddedFiles()) entries.Add((f.Key, JsonValue.Parse(f.Value).AsObject()));
            foreach (var (file, o) in entries.OrderBy(x => x.O.GetInt("listOrder", 1000)).ThenBy(x => x.O.GetString("id"), StringComparer.Ordinal))
                foreach (var q in o.GetObject("quantities"))
                {
                    var qo = q.Value.AsObject();
                    var vals = qo.Where(kv => !Meta.Contains(kv.Key)).Select(kv => kv.Key + " = " + Value(kv.Value));
                    var cond = qo.GetObject("conditions");
                    string unc = !qo.Has("relativeUncertainty") ? qo.GetString("uncertainty", "") : "about " + Num(100 * qo.GetDouble("relativeUncertainty", 0)) + " %" + (qo.Has("uncertainty") ? "; " + qo.GetString("uncertainty") : "");
                    string conditions = cond != null && cond.Any() ? " (" + string.Join(", ", cond.Select(kv => kv.Key + " " + Value(kv.Value))) + ")" : "";
                    rows.Add(new Row { Entry = o.GetString("id"), Kind = o.GetString("kind"), Quantity = q.Key, Values = string.Join("; ", vals) + conditions,
                        Status = qo.GetString("status", qo.Has("ref") ? "see model" : "?"), Uncertainty = unc, Source = qo.GetString("source", qo.Has("ref") ? "the Raman model '" + qo.GetString("ref") + "'" : ""), Check = qo.GetString("verification", "") });
                }

            var sb = new StringBuilder();
            sb.AppendLine("# Material catalogue");
            sb.AppendLine();
            sb.AppendLine("*Generated by `ultrafast reference materials` from `src/UltrafastEngine.Core/Data/materials/`; do not edit. Change a number in its catalogue file, then run `/regen`.*");
            sb.AppendLine();
            sb.AppendLine("Every number the engine takes from its material library is listed here with its unit (in the key name), its **status**, its uncertainty and its source.");
            sb.AppendLine("How the files work, how to override a value and how runs report the values they used: [Materials](materials.md#the-material-catalogue).");
            sb.AppendLine();
            sb.AppendLine("| status | meaning |");
            sb.AppendLine("|---|---|");
            sb.AppendLine("| `verified` | the number was read from the cited source and compared; the comparison is recorded (`check`) |");
            sb.AppendLine("| `approximate` | a typical, rounded or fitted value, good to the stated uncertainty; not traced to one table |");
            sb.AppendLine("| `unverified` | not checked against any source; quoted from memory or from an earlier version of the code |");
            sb.AppendLine();
            sb.AppendLine("A run that uses an `approximate` or `unverified` value says so in its notes and lists it under `unverifiedInputs` in `summary.json`.");
            sb.AppendLine();
            int n = rows.Count, v = rows.Count(r => r.Status == "verified"), a = rows.Count(r => r.Status == "approximate"), u = rows.Count(r => r.Status == "unverified");
            sb.AppendLine("**" + n + " quantities in " + entries.Count + " entries: " + v + " verified, " + a + " approximate, " + u + " unverified.**");
            sb.AppendLine();

            foreach (var (kind, title) in new[] { ("solid", "Solids and liquids"), ("gas", "Gases"), ("raman", "Raman models"), ("gain", "Gain media"), ("crystal", "chi(2) crystals"), ("default", "Generic defaults (used when a run does not give the value)") })
            {
                sb.AppendLine("## " + title);
                sb.AppendLine();
                foreach (var g in rows.Where(r => r.Kind == kind).GroupBy(r => r.Entry))
                {
                    var o = entries.First(e => e.O.GetString("id") == g.Key).O;
                    sb.AppendLine("### " + g.Key);
                    sb.AppendLine();
                    sb.Append(o.GetString("description", ""));
                    var al = o.GetArray("aliases")?.Select(x => x.AsString()).Where(x => x.Length > 0).ToList();
                    if (al != null && al.Count > 0) sb.Append(". Aliases: " + string.Join(", ", al.Select(x => "`" + x + "`")));
                    sb.AppendLine(".");
                    if (o.Has("notes")) { sb.AppendLine(); sb.AppendLine(o.GetString("notes") + (o.GetString("notes").EndsWith(".") ? "" : ".")); }
                    sb.AppendLine();
                    sb.AppendLine("| quantity | values | status | uncertainty | source |");
                    sb.AppendLine("|---|---|---|---|---|");
                    foreach (var r in g)
                        sb.AppendLine("| `" + r.Quantity + "` | " + Cell(r.Values) + " | " + r.Status + " | " + Cell(r.Uncertainty) + " | " + Cell(r.Source + (r.Check.Length > 0 ? " Check: " + r.Check + "." : "")) + " |");
                    sb.AppendLine();
                }
            }

            sb.AppendLine("## Not verified yet");
            sb.AppendLine();
            sb.AppendLine("The to-do list for anyone with the papers: every quantity whose status is not `verified`.");
            sb.AppendLine();
            sb.AppendLine("| entry | quantity | status | what to check |");
            sb.AppendLine("|---|---|---|---|");
            foreach (var r in rows.Where(r => r.Status == "approximate" || r.Status == "unverified"))
                sb.AppendLine("| " + r.Entry + " | `" + r.Quantity + "` | " + r.Status + " | " + Cell(r.Source) + " |");
            return sb.ToString();
        }
    }
}
