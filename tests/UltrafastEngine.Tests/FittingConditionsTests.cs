        [Test(Category = "fitting", Reference = "synthetic: shared filter parameters generated by the same forward model", Tolerance = "1e-3 relative")]
        public void Conditions_TwoInputPulses_RecoverTheSharedFilter()
        {
            var dir = TempDir();
            var truth = Filter(8.0, 1034.0);
            WriteSpectrum(dir, Truth(Sys(truth), Gauss(Lam, 100e-15, 1e-6)), "a.csv");
            WriteSpectrum(dir, Truth(Sys(truth), Gauss(Lam, 40e-15, 1e-6)), "b.csv");
            var sys = Sys(Filter(O("value", 12.0, "fit", true, "min", 2.0, "max", 30.0), O("value", 1030.0, "fit", true, "min", 1020.0, "max", 1040.0)));
            var r = Fit(sys, dir, Gauss(Lam, 100e-15, 1e-6), O("freezeGrid", false, "conditions", A(Cond("long", "a.csv", 100), Cond("short", "b.csv", 40))), Measured("a.csv"));
            var f = r.Fit();
            Assert.Close(8.0, f.Parameters.First(p => p.Name.EndsWith("fwhmNm")).Value, 1e-3, 0, "shared FWHM");
            Assert.Close(1034.0, f.Parameters.First(p => p.Name.EndsWith("centerWavelengthNm")).Value, 1e-4, 0, "shared centre");
            Assert.Equal(2, f.Parameters.Count, "no per-condition copies of shared parameters");
            Assert.Equal(2, f.Conditions.Count, "two condition reports");
            Assert.True(f.PerInstrument.ContainsKey("long/spec") && f.PerInstrument.ContainsKey("short/spec"), "instruments are reported as condition/instrument");
            Assert.True(f.Influence.Values.First().ContainsKey("short/spec"), "influence map names conditions");
            double both = f.Influence.Values.First()["long/spec"] + f.Influence.Values.First()["short/spec"];
            Assert.Close(1.0, both, 1e-9, 0, "all information comes from the two spectra");
            r.WriteAll(Path.Combine(dir, "out"));
            Assert.True(File.Exists(Path.Combine(dir, "out", "fitted-conditions.json")), "fitted-conditions.json is written");
        }

