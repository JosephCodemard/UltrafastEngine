        private static JsonObject Tr(string id, params JsonObject[] ops) { var o = O("id", id, "type", "transform"); o.Set("operators", new JsonArray(ops)); return o; }
        private static JsonObject Filter(JsonValue fwhm, JsonValue centre) => Tr("filter", O("kind", "spectralAmplitude", "shape", "gaussian", "fwhmNm", fwhm, "centerWavelengthNm", centre));

        /// <summary>Write the spectrometer reading of a run as a CSV (optionally with seeded noise of the given relative rms).</summary>
        private static void WriteSpectrum(string dir, RunResult r, string file, double noise = 0, int seed = 1)
        {
            var ins = r.Instruments.First(i => i.Name == "spec");
            var x = ins.Arrays.First(a => a.Name.EndsWith("_wavelength_m")).Data; var y = ins.Arrays.First(a => a.Name.EndsWith("_spectrum")).Data;
            double max = y.Max(); var rnd = new Random(seed);
            using (var w = new StreamWriter(Path.Combine(dir, file)))
            {
                w.WriteLine("wavelength_nm,intensity");
                for (int i = 0; i < x.Length; i += 4)
                {
                    double g = Math.Sqrt(-2 * Math.Log(1 - rnd.NextDouble())) * Math.Cos(2 * Math.PI * rnd.NextDouble());
                    w.WriteLine((x[i] * 1e9).ToString("R", CultureInfo.InvariantCulture) + "," + (y[i] + noise * max * g).ToString("R", CultureInfo.InvariantCulture));
                }
            }
        }

        private static JsonObject Spec1(double resolutionM = 0.2e-9) => O("kind", "spectrometer", "name", "spec", "resolutionM", resolutionM);
        private static RunResult Truth(SystemDescription sys, JsonObject pulse, double resolutionM = 0.2e-9) =>
            Go(sys, Spec(pulse, O("grid", Grid, "instruments", A(Spec1(resolutionM)))));

        private static JsonObject Measured(string file, double sigma = 0.01, double resolutionM = 0.2e-9)
        {
            var o = Spec1(resolutionM); o.Set("measured", O("file", file, "sigma", sigma)); return o;
        }

        private static JsonObject Cond(string name, string file, double durationFs, bool held = false, params (string, double)[] vars)
        {
            var c = O("name", name, "heldOut", held, "set", O("pulse/durationFwhmS", durationFs * 1e-15, "instrument:spec/measured/file", file));
            if (vars.Length > 0) { var v = new JsonObject(); foreach (var (k, x) in vars) v.Set(k, x); c.Set("variables", v); }
            return c;
        }

        private static RunResult Fit(SystemDescription sys, string dir, JsonObject pulse, JsonObject fit, JsonObject spectrometer)
        {
            var run = RunSpec.FromJson(O("format", "ultrafast-run", "pulse", pulse, "grid", Grid, "fit", fit, "instruments", A(spectrometer)), dir);
            return Go(sys, run);
        }

