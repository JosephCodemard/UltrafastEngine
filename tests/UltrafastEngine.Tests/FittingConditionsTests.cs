        [Test(Category = "fitting", Reference = "chi^2 per point of an unfitted condition near 1 when the model is right", Tolerance = "chi^2/point < 1.5 with noise equal to the stated sigma")]
        public void Conditions_HeldOutCondition_IsPredictedWithinTheNoise()
        {
            var dir = TempDir();
            var truth = Sys(Filter(8.0, 1034.0));
            WriteSpectrum(dir, Truth(truth, Gauss(Lam, 100e-15, 1e-6)), "a.csv", 0.01, 1);
            WriteSpectrum(dir, Truth(truth, Gauss(Lam, 40e-15, 1e-6)), "b.csv", 0.01, 2);
