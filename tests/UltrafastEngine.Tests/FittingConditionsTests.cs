        private static readonly double[] KnotsNm = { 1018, 1026, 1034, 1042, 1050 };
        private static SystemDescription KnotSystem(double[] trans) => Sys(Tr("t", O("kind", "spectralAmplitude", "shape", "spline", "knots", O("wavelengthsNm", KnotsNm, "transmission", trans), "passive", false)));
        private static double[] TrueKnots(double theta) => new[] { 0.5 + 0.2 * theta, 0.8 - 0.1 * theta, 1.0 + 0.0 * theta, 0.7 + 0.15 * theta, 0.4 - 0.1 * theta };

        [Test(Category = "fitting", Reference = "synthetic: five spectral knots, each linear in a condition variable", Tolerance = "0.01 absolute on the knots relative to the central one")]
        public void Surface_KnownSmoothSurface_IsRecoveredAcrossSpectrumAndCondition()
        {
            var dir = TempDir();
            var thetas = new[] { -1.0, -0.33, 0.33, 1.0 };
            var conds = new JsonArray();
            for (int k = 0; k < thetas.Length; k++)
            {
                WriteSpectrum(dir, Truth(KnotSystem(TrueKnots(thetas[k])), Gauss(Lam, 40e-15, 1e-6)), "s" + k + ".csv");
                conds.Add(O("name", "T" + k, "variables", O("theta", thetas[k]), "set", O("instrument:spec/measured/file", "s" + k + ".csv")));
            }
            var fit = O("freezeGrid", false, "maxIterations", 60, "conditions", conds, "surfaces", A(O("name", "trans", "pathTemplate", "element:t/operators/0/knots/transmission/{i}", "count", 5,
                "kind", "chebyshev", "degree", 1, "variable", "theta", "range", A(-1.0, 1.0), "coefficients", A(O("initial", 0.7, "scale", 0.3, "min", -2.0, "max", 3.0), O("initial", 0.0, "scale", 0.2, "min", -2.0, "max", 2.0)))));
            var r = Fit(KnotSystem(new[] { 0.7, 0.7, 0.7, 0.7, 0.7 }), dir, Gauss(Lam, 40e-15, 1e-6), fit, Measured("s0.csv", 1e-3));
            var f = r.Fit();
            Assert.Equal(10, f.Parameters.Count, "five knots x two orders");
            // the fit must reproduce the spectra
            for (int k = 0; k < thetas.Length; k++)
                Assert.Less(f.Conditions[k].ReducedChi2, 1.0, "condition " + k + " is described");
            r.WriteAll(Path.Combine(dir, "out"));
            var dep = JsonValue.ParseFile(Path.Combine(dir, "out", "fitted-conditions.json")).AsObject().GetArray("dependences")[0].AsObject();
            var at = Dependence.Evaluate(dep, 0.0);
            var truth0 = TrueKnots(0.0);
            // a spectrometer reading is normalised: only the shape of the transmission is determined, so compare with the central knot
            double c0 = at["element:t/operators/0/knots/transmission/2"];
            for (int i = 0; i < 5; i++)
                Assert.Close(truth0[i] / truth0[2], at["element:t/operators/0/knots/transmission/" + i] / c0, 0, 0.01, "knot " + i + " relative to the central knot at theta = 0 (an interpolated condition)");
        }

        [Test(Category = "fitting")]
        public void Surface_SmoothnessPenalty_ReducesTheErrorOfASurfaceFittedToNoisyData()
        {
            var dir = TempDir();
            var thetas = new[] { -1.0, -0.5, 0.0, 0.5, 1.0 };
            // a smooth truth in both directions: a Gaussian-like transmission that drifts with the condition
            double[] Smooth(double th) => KnotsNm.Select(l => 0.2 + 0.8 * Math.Exp(-Math.Pow((l - 1034 - 4 * th) / 14, 2))).ToArray();
            var conds = new JsonArray();
            for (int k = 0; k < thetas.Length; k++)
            {
                WriteSpectrum(dir, Truth(KnotSystem(Smooth(thetas[k])), Gauss(Lam, 40e-15, 1e-6)), "n" + k + ".csv", 0.1, 10 + k);
                conds.Add(O("name", "T" + k, "variables", O("theta", thetas[k]), "set", O("instrument:spec/measured/file", "n" + k + ".csv")));
            }
            double Error(double wPaths, double wVar)
            {
                var fit = O("freezeGrid", false, "maxIterations", 60, "conditions", conds, "surfaces", A(O("name", "trans", "pathTemplate", "element:t/operators/0/knots/transmission/{i}", "count", 5,
                    "kind", "chebyshev", "degree", 3, "variable", "theta", "range", A(-1.0, 1.0), "smoothnessPaths", wPaths, "smoothnessVariable", wVar,
                    "coefficients", A(O("initial", 0.6, "scale", 0.3), O("scale", 0.2), O("scale", 0.2), O("scale", 0.2)))));
                var r = Fit(KnotSystem(new[] { 0.6, 0.6, 0.6, 0.6, 0.6 }), dir, Gauss(Lam, 40e-15, 1e-6), fit, Measured("n0.csv", 0.1));
                r.WriteAll(Path.Combine(dir, "out" + wPaths.ToString("0.##", CultureInfo.InvariantCulture)));
                var dep = JsonValue.ParseFile(Path.Combine(dir, "out" + wPaths.ToString("0.##", CultureInfo.InvariantCulture), "fitted-conditions.json")).AsObject().GetArray("dependences")[0].AsObject();
                double e = 0; int n = 0;
                foreach (var th in new[] { -0.75, -0.25, 0.25, 0.75 })
                {
                    var at = Dependence.Evaluate(dep, th); var tr = Smooth(th);
                    double scale = at["element:t/operators/0/knots/transmission/2"] / tr[2];   // the reading is normalised: remove the common scale
                    for (int i = 0; i < 5; i++) { double d = at["element:t/operators/0/knots/transmission/" + i] / scale - tr[i]; e += d * d; n++; }
                }
                return Math.Sqrt(e / n);
            }
            double plain = Error(0, 0), smooth = Error(3.0, 3.0);
            Assert.Less(smooth, plain, "the penalised surface is closer to the truth");
        }

