#!/usr/bin/env python3
"""Assemble docs/gallery.md from the figures and animations committed next to the examples.

    python build/gallery.py            # writes docs/gallery.md
    python build/gallery.py --check    # exit 1 if the committed page is out of date
    python build/gallery.py --hero 4f-correlator    # also copy that example's animation.gif to assets/hero.gif (for the README)

An example takes part when its folder (docs/examples/<Group>/<name>/) holds a ``hero.png`` and/or an ``animation.gif`` -- the files
``make_figures.py`` writes for examples whose story needs a purpose-made figure (see docs/examples/make_all.py). The title and the first
sentence come from the example's README.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "docs" / "examples"
OUT = ROOT / "docs" / "gallery.md"
GROUPS = ["GettingStarted", "LaserSystems", "Nonlinear", "Diffraction", "Wavefronts", "Branched", "Diagnostics", "Components", "Computing",
          "AdaptiveOptics", "DigitalTwin", "Interop"]


def summary(readme: Path) -> tuple:
    text = readme.read_text(encoding="utf-8").splitlines()
    title = next((l[2:].strip() for l in text if l.startswith("# ")), readme.parent.name)
    para = []
    for l in text[1:]:
        if l.startswith(("#", "!", "```", "|")):
            if para:
                break
            continue
        if l.strip():
            para.append(l.strip())
        elif para:
            break
    first = re.split(r"(?<=[.!?])\s", " ".join(para), maxsplit=1)[0] if para else ""
    return title, re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", first)


def build() -> str:
    out = ["# Gallery", "",
           "Figures and animations made by the examples. Generated by `python build/gallery.py` from the `hero.png` and `animation.gif` files next to the "
           "example READMEs; `python docs/examples/make_all.py` redraws them. Each animation is at most 2.5 MB, each figure at most 300 kB.", ""]
    found = 0
    for g in GROUPS:
        items = []
        for d in sorted((EXAMPLES / g).glob("*/")) if (EXAMPLES / g).is_dir() else []:
            if (d / "README.md").exists() and ((d / "hero.png").exists() or (d / "animation.gif").exists()):
                items.append(d)
        if not items:
            continue
        out += ["## " + g, ""]
        for d in items:
            title, first = summary(d / "README.md")
            rel = d.relative_to(ROOT / "docs").as_posix()
            out += ["### [%s](%s/README.md)" % (title, rel), ""]
            if first:
                out += [first, ""]
            for f, alt in (("hero.png", "figure"), ("animation.gif", "animation")):
                if (d / f).exists():
                    out += ["![%s: %s](%s/%s)" % (title, alt, rel, f), ""]
            found += 1
    if not found:
        out += ["No example has committed figures yet.", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--hero", metavar="EXAMPLE", help="copy this example's animation.gif to assets/hero.gif")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/gallery.md is out of date: run python build/gallery.py")
            return 1
        print("docs/gallery.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s" % OUT)
    if a.hero:
        src = next((p for p in EXAMPLES.glob("*/*/animation.gif") if p.parent.name == a.hero or p.parent.relative_to(EXAMPLES).as_posix() == a.hero), None)
        if src is None:
            print("no animation.gif for '%s'" % a.hero)
            return 2
        shutil.copy2(src, ROOT / "assets" / "hero.gif")
        print("copied %s -> assets/hero.gif (%d kB)" % (src.relative_to(ROOT), src.stat().st_size // 1000))
    return 0


if __name__ == "__main__":
    sys.exit(main())
